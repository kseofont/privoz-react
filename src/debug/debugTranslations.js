export function debugText(lang, key) {
  const normalized = ['en', 'ru', 'ua', 'es'].includes(lang) ? lang : 'en';
  return TEXT[normalized]?.[key] || TEXT.en[key] || key;
}

export function getDebugFieldMeta(key, lang = 'en') {
  const normalized = ['en', 'ru', 'ua', 'es'].includes(lang) ? lang : 'en';
  const meta = FIELD_META[key] || {};
  return {
    icon: meta.icon || '🔧',
    label: meta.labels?.[normalized] || meta.labels?.en || key,
    description:
      meta.desc?.[normalized] || meta.desc?.en || TEXT[normalized]?.genericFieldDescription || TEXT.en.genericFieldDescription,
  };
}

export function localizeDebugValue(value, lang = 'en') {
  if (value === null || value === undefined || value === '') return '—';
  if (typeof value !== 'object' || Array.isArray(value)) return String(value);
  const localizedKeys = ['en', 'ru', 'ua', 'es'];
  if (localizedKeys.some(key => Object.prototype.hasOwnProperty.call(value, key))) {
    return value[lang] || value.en || value.ru || value.ua || value.es || '—';
  }
  return null;
}
